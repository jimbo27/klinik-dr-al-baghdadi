// Builds dist/assets.js: the pages, minified browser JS and CSS as strings the
// Worker serves directly (no separate static hosting). Run by `wrangler deploy`
// (see [build] in wrangler.toml) and by `npm test`.
import { build, transform } from "esbuild";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const here = (p) => new URL(p, import.meta.url);
const read = (p) => readFile(here(p), "utf8");

// Version stamp, e.g. 20261123153012 (Malaysia time). Pages poll /api/version and
// reload when it changes, so staff phones pick up new deploys by themselves.
const VERSION = new Date(Date.now() + 8 * 3600e3).toISOString().replace(/\D/g, "").slice(0, 14);

const bundle = async (entry) => {
  const out = await build({
    entryPoints: [fileURLToPath(here(entry))],
    bundle: true,
    minify: true,
    format: "iife",
    target: "es2020",
    write: false,
  });
  return out.outputFiles[0].text;
};

const html = async (p) =>
  (await read(p))
    .replace(/__VERSION__/g, VERSION)
    .replace(/\s+/g, " ") // no <pre>/<textarea> in these pages, so all whitespace can collapse
    .replace(/>\s+</g, "><")
    .replace(/\s+(\/?>)/g, "$1")
    .trim();

const assets = {
  "index.html": await html("src/client/index.html"),
  "admin.html": await html("src/client/admin.html"),
  "app.js": await bundle("src/client/app.js"),
  "admin.js": await bundle("src/client/admin.js"),
  "style.css": (await transform(await read("src/client/style.css"), { loader: "css", minify: true })).code,
  "icon.svg": (await read("src/client/icon.svg")).trim(),
  "manifest.webmanifest": JSON.stringify(JSON.parse(await read("src/client/manifest.webmanifest"))),
};

await mkdir(here("dist/"), { recursive: true });
await writeFile(
  here("dist/assets.js"),
  `// Generated by build.mjs. Do not edit.\nexport const VERSION = ${JSON.stringify(VERSION)};\nexport const ASSETS = ${JSON.stringify(assets)};\n`,
);
console.log(`Built dist/assets.js (version ${VERSION})`);
